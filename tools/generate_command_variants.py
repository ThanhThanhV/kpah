        "        PacketReader in = new PacketReader(payload); int count = in.readU8();",
        "        List<Map<String, Object>> records = new ArrayList<>();",
        "        for (int i = 0; i < count; i++) {",
        "            Map<String, Object> record = new LinkedHashMap<>();",
