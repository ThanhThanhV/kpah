#!/usr/bin/env python3
"""Generate source-backed C2S command variant codecs from protocol/protocol.yaml."""
from __future__ import annotations
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "protocol" / "protocol.yaml"
JS = ROOT / "src" / "protocol" / "generated" / "command-variant-codec.js"
JAVA = ROOT / "protocol" / "generated" / "java" / "com" / "kpah" / "protocol" / "generated" / "ProtocolCommandVariantCodec.java"
TYPES = {"i8": ("writeI8", "readI8", "byteValue"), "i16": ("writeI16", "readI16", "shortValue"),
         "i32": ("writeI32", "readI32", "intValue"), "utf": ("writeUTF", "readUTF", None)}

def load():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    schemas = [s for s in spec.get("commandVariantSchemas", []) if s.get("direction") == "C2S" and s.get("opcode") == 62]
    if len(schemas) != 1:
        raise ValueError("Expected exactly one C2S opcode 62 commandVariantSchema")
    schema = schemas[0]
    modes = set()
    for variant in schema.get("variants", []):
        mode = int(variant["mode"])
        if mode in modes:
            raise ValueError(f"Duplicate opcode 62 mode {mode}")
        modes.add(mode)
        for field in variant.get("fields", []):
            if field["type"] not in TYPES:
                raise ValueError(f"Unsupported opcode 62 field type {field['type']}")
    if modes != {0, 2, 3, 4, 5, 6, 7}:
        raise ValueError(f"Unexpected source-backed opcode 62 modes: {sorted(modes)}")
    return schema

def js_output(schema):
    lines = [
        "// Generated by tools/generate_command_variants.py. Do not edit.",
        'import { PacketReader, PacketWriter } from "./packet-codec.js";',
        "function readRemaining(reader) { const out = new Uint8Array(reader.remaining()); for (let i = 0; i < out.length; i += 1) out[i] = reader.readU8(); return out; }",
        "export const C2S_OPCODE62_MODES = Object.freeze([0, 2, 3, 4, 5, 6, 7]);",
        "export function encodeC2SOpcode62(values) {",
        '  if (!values || !Number.isInteger(values.mode)) throw new TypeError("opcode 62 values.mode required");',
        "  const writer = new PacketWriter().writeI8(values.mode);",
        "  switch (values.mode) {"
    ]
    for v in schema["variants"]:
        lines.append(f'    case {int(v["mode"])}:')
        for field in v.get("fields", []):
            name, typ = field["name"], field["type"]
            if typ == "utf":
                lines.append(f'      if (!("{name}" in values)) throw new Error("Missing field {name}");')
                lines.append(f'      writer.writeUTF(values.{name});')
            else:
                lines.append(f'      if (!("{name}" in values)) throw new Error("Missing field {name}");')
                lines.append(f'      writer.{TYPES[typ][0]}(values.{name});')
        lines.append("      break;")
    lines += ['    default: throw new RangeError("Unsupported C2S opcode 62 mode: " + values.mode);',
              "  }", "  return writer.toUint8Array();", "}",
              "export function decodeC2SOpcode62(payload) {",
              "  const reader = new PacketReader(payload), mode = reader.readI8(), fields = {};",
              "  switch (mode) {"]
    for v in schema["variants"]:
        lines.append(f'    case {int(v["mode"])}:')
        for field in v.get("fields", []):
            name, typ = field["name"], field["type"]
            lines.append(f'      fields.{name} = reader.{TYPES[typ][1]}();')
        lines.append("      break;")
    lines += ['    default: return { mode, fields: null, unconsumedBytes: readRemaining(reader), trailingBytes: new Uint8Array() };',
              '  }',
              '  return { mode, fields, unconsumedBytes: new Uint8Array(), trailingBytes: readRemaining(reader) };',
              "}", ""]
    return "\n".join(lines)

def java_output(schema):
    lines = [
        "// Generated by tools/generate_command_variants.py. Do not edit.",
        "package com.kpah.protocol.generated;",
        "import java.io.IOException;",
        "import java.util.LinkedHashMap;",
        "import java.util.Map;",
        "public final class ProtocolCommandVariantCodec {",
        "    private ProtocolCommandVariantCodec() {}",
        "    public record Decoded(int mode, Map<String,Object> fields, byte[] unconsumedBytes, byte[] trailingBytes) {}",
        "    public static byte[] encodeC2SOpcode62(int mode, Map<String,Object> values) throws IOException {",
        "        if(values==null) throw new IllegalArgumentException(\"values required\");",
        "        PacketWriter out=new PacketWriter(); out.writeI8(mode);",
        "        switch(mode) {"
    ]
    for v in schema["variants"]:
        lines.append(f'            case {int(v["mode"])} -> {{')
        for field in v.get("fields", []):
            name, typ = field["name"], field["type"]
            if typ == "utf":
                lines.append(f'                if(!values.containsKey("{name}")) throw new IllegalArgumentException("Missing field {name}");')
                lines.append(f'                out.writeUTF((String)values.get("{name}"));')
            else:
                method = TYPES[typ][0]
                cast = TYPES[typ][2]
                lines.append(f'                if(!values.containsKey("{name}")) throw new IllegalArgumentException("Missing field {name}");')
                lines.append(f'                out.{method}(((Number)values.get("{name}")).{cast}());')
        lines.append("            }")
    lines += ['            default -> throw new IllegalArgumentException("Unsupported C2S opcode 62 mode: "+mode);',
              "        }", "        return out.toByteArray();", "    }",
              "    public static Decoded decodeC2SOpcode62(byte[] payload) throws IOException {",
              "        PacketReader in=new PacketReader(payload); int mode=in.readI8(); Map<String,Object> fields=new LinkedHashMap<>();",
              "        switch(mode) {"]
    for v in schema["variants"]:
        lines.append(f'            case {int(v["mode"])} -> {{')
        for field in v.get("fields", []):
            name, typ = field["name"], field["type"]
            lines.append(f'                fields.put("{name}", in.{TYPES[typ][1]}());')
        lines.append("            }")
    lines += ['            default -> { return new Decoded(mode, Map.of(), readRemaining(in), new byte[0]); }',
              "        }", "        return new Decoded(mode, Map.copyOf(fields), new byte[0], readRemaining(in));",
              "    }",
              "    private static byte[] readRemaining(PacketReader in) throws IOException {",
              "        byte[] bytes=new byte[in.remaining()]; for(int i=0;i<bytes.length;i++) bytes[i]=(byte)in.readU8(); return bytes;",
              "    }", "}", ""]
    return "\n".join(lines)

def outputs():
    schema = load()
    return {JS: js_output(schema), JAVA: java_output(schema)}

def main():
    parser=argparse.ArgumentParser(); parser.add_argument("--check",action="store_true"); args=parser.parse_args()
    stale=[]
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding="utf-8")
    if stale: raise SystemExit("Stale command-variant outputs: "+", ".join(stale))
    print("Command-variant codec "+("check" if args.check else "generated")+": 2 files")
if __name__ == "__main__": main()
