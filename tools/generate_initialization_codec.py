def outputs():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    schemas = spec.get("modeSchemas", [])
    seen = set()
    for schema in schemas:
        key = (schema["direction"], int(schema["opcode"]), int(schema["mode"]))
        if key in seen:
            raise ValueError(f"Duplicate mode schema: {key}")
        seen.add(key)
        if schema["direction"] != "S2C":
            raise ValueError("Mode decoder currently supports S2C only")
        mode = int(schema["mode"])
        if mode in (0, 1):
            if schema.get("commonFields") != [
                {"name": "aY", "type": "i32"},
                {"name": "aZ", "type": "i32"},
            ]:
                raise ValueError("Unsupported verified common opcode 16 fields")
        elif mode == 2:
            if schema.get("fields") != [{"name": "aY", "type": "i32"}] or schema.get("commonFields") != [
                {"name": "aZ", "type": "i32"}
            ]:
                raise ValueError("Unsupported mode 2 common fields")
        if mode == 0:
            if schema["fields"] != [{"name": "currency", "type": "i64"}]:
                raise ValueError("Unsupported mode 0 fixed fields")
            records = schema["records"]
            if records["countType"] != "u8" or records["fields"] != [
                {"name": "skillIndex", "type": "u8"},
                {"name": "skillValue", "type": "i32"},
            ]:
                raise ValueError("Unsupported mode 0 skill record schema")
        elif mode == 1:
            if schema["fields"] != [
                {"name": "itemCount", "type": "i16"},
                {"name": "items", "type": "bo-records"},
            ]:
                raise ValueError("Unsupported mode 1 inventory record schema")
        elif mode == 2:
            if schema.get("groups") != [
                {"name": "firstCollection", "countType": "i8", "record": "k-first"},
                {"name": "secondCollection", "countType": "i8", "record": "k-second"},
            ]:
                raise ValueError("Unsupported mode 2 auxiliary record schema")
        else:
            raise ValueError(f"Unsupported generated opcode 16 mode: {mode}")

    js_schemas = json.dumps(schemas, ensure_ascii=False, separators=(",", ":"))
