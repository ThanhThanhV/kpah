#!/usr/bin/env python3
"""Generate evidence-bounded mode decoders for partially understood S2C packets."""
from __future__ import annotations
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "protocol/protocol.yaml"
JS = ROOT / "src/protocol/generated/initialization-codec.js"
JAVA = ROOT / "protocol/generated/java/com/kpah/protocol/generated/ProtocolInitializationCodec.java"

def outputs():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    schemas = spec.get("modeSchemas", [])
    seen = set()
    for schema in schemas:
        key = (schema["direction"], int(schema["opcode"]), int(schema["mode"]))
        if key in seen:
            raise ValueError(f"Duplicate mode schema: {key}")
        seen.add(key)
        if schema["direction"] != "S2C":
            raise ValueError("Mode decoder currently supports S2C only")
        if schema["fields"] != [{"name": "currency", "type": "i64"}]:
            raise ValueError("Unsupported verified fixed fields")
        if schema.get("commonFields") != [
            {"name": "aY", "type": "i32"},
            {"name": "aZ", "type": "i32"},
        ]:
            raise ValueError("Unsupported verified common opcode 16 fields")
        records = schema["records"]
        if records["countType"] != "u8" or records["fields"] != [
            {"name": "skillIndex", "type": "u8"},
            {"name": "skillValue", "type": "i32"},
        ]:
            raise ValueError("Unsupported verified repeated record schema")

    js_schemas = json.dumps(schemas, ensure_ascii=False, separators=(",", ":"))
    js = r'''// Generated by tools/generate_initialization_codec.py. Do not edit.
import { PacketReader } from "./packet-codec.js";
export const INITIALIZATION_MODE_SCHEMAS = Object.freeze(__SCHEMAS__);
export function decodeS2CInitialization(opcode, payload) {
  const schema = INITIALIZATION_MODE_SCHEMAS.find(s => s.direction === "S2C" && s.opcode === opcode);
  if (!schema) throw new Error("No verified mode schema for S2C opcode " + opcode);
  const reader = new PacketReader(payload);
  const mode = reader.readU8();
  if (mode !== schema.mode) {
    const opaquePayload = new Uint8Array(reader.remaining());
    for (let i = 0; i < opaquePayload.length; i += 1) opaquePayload[i] = reader.readU8();
    return { mode, decoded: false, opaquePayload };
  }
  const currency = reader.readI64();
  const skillCount = reader.readU8();
  const skills = [];
  for (let i = 0; i < skillCount; i += 1) {
    skills.push({ skillIndex: reader.readU8(), skillValue: reader.readI32() });
  }
  const aY = reader.readI32();
  const aZ = reader.readI32();
  const trailingBytes = new Uint8Array(reader.remaining());
  for (let i = 0; i < trailingBytes.length; i += 1) trailingBytes[i] = reader.readU8();
  return { mode, decoded: true, currency, skills, aY, aZ, trailingBytes };
}
'''.replace("__SCHEMAS__", js_schemas)

    java = r'''// Generated by tools/generate_initialization_codec.py. Do not edit.
package com.kpah.protocol.generated;
import java.io.IOException;
import java.util.*;
public final class ProtocolInitializationCodec {
    private ProtocolInitializationCodec() {}
    public record SkillValue(int skillIndex, int skillValue) {}
    public record Decoded(int mode, boolean decoded, Long currency, List<SkillValue> skills,
                          Integer aY, Integer aZ, byte[] opaquePayload, byte[] trailingBytes) {}
    public static Decoded decodeS2COpcode16(byte[] payload) throws IOException {
        PacketReader in = new PacketReader(payload);
        int mode = in.readU8();
        if (mode != 0) {
            byte[] opaque = new byte[in.remaining()];
            for (int i = 0; i < opaque.length; i++) opaque[i] = (byte) in.readU8();
            return new Decoded(mode, false, null, List.of(), null, null, opaque, new byte[0]);
        }
        long currency = in.readI64();
        int count = in.readU8();
        List<SkillValue> skills = new ArrayList<>(count);
        for (int i = 0; i < count; i++) {
            skills.add(new SkillValue(in.readU8(), in.readI32()));
        }
        int aY = in.readI32();
        int aZ = in.readI32();
        byte[] trailing = new byte[in.remaining()];
        for (int i = 0; i < trailing.length; i++) trailing[i] = (byte) in.readU8();
        return new Decoded(mode, true, currency, List.copyOf(skills), aY, aZ, new byte[0], trailing);
    }
}
'''
    return {JS: js, JAVA: java}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale initialization outputs: " + ", ".join(stale))
    print("Initialization codec " + ("check" if args.check else "generated") + ": 2 files")

if __name__ == "__main__":
    main()
