#!/usr/bin/env python3
"""Generate evidence-bounded prefix decoders for partially understood S2C payloads."""
from __future__ import annotations
import argparse, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "protocol/protocol.yaml"
JS = ROOT / "src/protocol/generated/prefix-codec.js"
JAVA = ROOT / "protocol/generated/java/com/kpah/protocol/generated/ProtocolPrefixCodec.java"
TYPES = {"u8", "i8", "i16", "i32", "bool", "utf", "u8bytes"}

def outputs():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    schemas = spec.get("prefixSchemas", [])
    seen = set()
    for s in schemas:
        key = (s["direction"], int(s["opcode"]))
        if key in seen: raise ValueError(f"Duplicate prefix schema: {key}")
        seen.add(key)
        if s["direction"] != "S2C": raise ValueError("Prefix decoder currently supports S2C only")
        for f in s["fields"]:
            if f["type"] not in TYPES: raise ValueError(f"Unsupported prefix field type: {f['type']}")
    js_schemas = json.dumps(schemas, ensure_ascii=False, separators=(",", ":"))
    js = r'''// Generated by tools/generate_prefix_protocol.py. Do not edit.
import { PacketReader } from "./packet-codec.js";
export const PREFIX_SCHEMAS = Object.freeze(__SCHEMAS__);
const READ = {
  u8: r => r.readU8(), i8: r => r.readI8(), i16: r => r.readI16(),
  i32: r => r.readI32(), bool: r => r.readBool(), utf: r => r.readUTF(),
  u8bytes: r => { const n = r.readU8(); const a = new Uint8Array(n); for (let i=0;i<n;i+=1) a[i]=r.readU8(); return a; }
};
export function decodeS2CPrefix(opcode, payload) {
  const schema = PREFIX_SCHEMAS.find(s => s.direction === "S2C" && s.opcode === opcode);
  if (!schema) throw new Error("No verified prefix schema for S2C opcode " + opcode);
  const reader = new PacketReader(payload), fields = {};
  for (const field of schema.fields) fields[field.name] = READ[field.type](reader);
  const trailingBytes = new Uint8Array(reader.remaining());
  for (let i=0;i<trailingBytes.length;i+=1) trailingBytes[i]=reader.readU8();
  return { fields, trailingBytes, decodedPrefixBytes: payload.length - trailingBytes.length };
}
'''.replace("__SCHEMAS__", js_schemas)
    java = r'''// Generated by tools/generate_prefix_protocol.py. Do not edit.
package com.kpah.protocol.generated;
import java.io.*;
import java.util.*;
public final class ProtocolPrefixCodec {
    private ProtocolPrefixCodec() {}
    public record Field(String name, String type) {}
    public record Schema(int opcode, String name, List<Field> fields) {}
    public record DecodedPrefix(Map<String,Object> fields, byte[] trailingBytes, int decodedPrefixBytes) {}
    private static final List<Schema> SCHEMAS = List.of(
__SCHEMA_ROWS__
    );
    public static DecodedPrefix decodeS2C(int opcode, byte[] payload) throws IOException {
        Schema schema = SCHEMAS.stream().filter(s -> s.opcode() == opcode).findFirst()
            .orElseThrow(() -> new IllegalArgumentException("No verified prefix schema for S2C opcode " + opcode));
        ByteArrayInputStream bytes = new ByteArrayInputStream(payload);
        DataInputStream in = new DataInputStream(bytes);
        Map<String,Object> fields = new LinkedHashMap<>();
        for (Field field : schema.fields()) {
            Object value = switch (field.type()) {
                case "u8" -> in.readUnsignedByte();
                case "i8" -> in.readByte();
                case "i16" -> in.readShort();
                case "i32" -> in.readInt();
                case "bool" -> in.readBoolean();
                case "utf" -> in.readUTF();
                case "u8bytes" -> { int n=in.readUnsignedByte(); byte[] a=new byte[n]; in.readFully(a); yield a; }
                default -> throw new IllegalStateException("Unsupported field type: " + field.type());
            };
            fields.put(field.name(), value);
        }
        int decoded = payload.length - bytes.available();
        byte[] trailing = bytes.readAllBytes();
        return new DecodedPrefix(Collections.unmodifiableMap(fields), trailing, decoded);
    }
    public static List<Schema> schemas() { return SCHEMAS; }
}
'''
    rows = []
    for s in schemas:
        fields = ", ".join(f'new Field("{f["name"]}", "{f["type"]}")' for f in s["fields"])
        rows.append(f'        new Schema({int(s["opcode"])}, "{s["name"]}", List.of({fields}))')
    java = java.replace("__SCHEMA_ROWS__", ",\n".join(rows))
    return {JS: js, JAVA: java}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale=[]
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content, encoding="utf-8")
    if stale: raise SystemExit("Stale prefix outputs: " + ", ".join(stale))
    print("Prefix protocol codec " + ("check" if args.check else "generated") + ": 2 files")
if __name__ == "__main__": main()
