def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content: stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(content, encoding="utf-8")
    if stale: raise SystemExit("Stale transport outputs: " + ", ".join(stale))
    print("Transport codec " + ("check" if args.check else "generated") + ": 2 files")
if __name__ == "__main__": main()
