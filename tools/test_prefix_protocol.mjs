import assert from "node:assert/strict";
import { decodeS2CPrefix, PREFIX_SCHEMAS } from "../src/protocol/generated/prefix-codec.js";
assert.equal(PREFIX_SCHEMAS.length, 1);
const b = [];
const u8 = n => b.push(n & 255);
const i16 = n => { const x=n&65535; b.push(x>>>8,x&255); };
const i32 = n => { const x=n>>>0; b.push(x>>>24,x>>>16&255,x>>>8&255,x&255); };
const utf = s => { const a=Array.from(s, c=>c.charCodeAt(0)); b.push(0,a.length,...a); };
i16(321); utf("Hero"); i32(100); i32(120); i32(40); i32(60); u8(2); u8(4);
i32(11); i32(12); i32(13); i16(21); i16(22); i16(23); u8(1); u8(0);
for(let n=0;n<8;n++) i16(n+30);
i32(99); i16(7); u8(3); u8(4); u8(5); u8(6); i16(8);
u8(9);u8(10);u8(11);u8(12);u8(3);u8(0xaa);u8(0xbb);u8(0xcc);i16(13);
u8(14);u8(15);u8(16);u8(17);u8(3); // unknown optional tail
const decoded=decodeS2CPrefix(3,Uint8Array.from(b));
assert.equal(decoded.fields.characterId,321);
assert.equal(decoded.fields.characterName,"Hero");
assert.equal(decoded.fields.currentHp,100);
assert.deepEqual([...decoded.fields.actionMapping],[0xaa,0xbb,0xcc]);
assert.equal(decoded.fields.cT,17);
assert.deepEqual([...decoded.trailingBytes],[3]);
assert.equal(decoded.decodedPrefixBytes,b.length-1);
assert.throws(()=>decodeS2CPrefix(1,new Uint8Array()),/No verified prefix schema/);
console.log("Generated S2C prefix codec: PASS (opcode 3, length-prefixed mapping, opaque tail)");
